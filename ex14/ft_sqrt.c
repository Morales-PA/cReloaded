int	ft_sqrt(int nb)
{
	int	i;

	if (nb == 0)
		return (0);
	if (nb == 1)
		return (1);
	i = 1;
	while (1)
	{
		if ((i * i) == nb)
		{
			return (i);
		}
		if ((i * i) > nb)
		{
			return (0);
		}
		i++;
	}
}
